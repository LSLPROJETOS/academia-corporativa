create or replace view public.member_directory as
select id, internal_id, name, role, dept, job_title, points, xp, badges, theme,
       created_at, last_login, streak, last_checkin
from public.profiles;
grant select on public.member_directory to authenticated;

create table if not exists public.app_records (
  id bigint generated by default as identity primary key,
  collection text not null,
  record_id text not null,
  owner_id uuid references auth.users(id) on delete cascade,
  owner_scope uuid generated always as
    (coalesce(owner_id, '00000000-0000-0000-0000-000000000000'::uuid)) stored,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (collection, record_id, owner_scope)
);

create index if not exists app_records_owner_collection_idx
  on public.app_records (owner_id, collection);
create index if not exists app_records_collection_idx
  on public.app_records (collection);

create or replace function public.has_course_enrollment(p_course_id text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.app_records
    where collection = 'enrollments'
      and owner_id = auth.uid()
      and payload ->> 'courseId' = p_course_id
  );
$$;

create or replace function public.can_view_course(p_course_id text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_platform_staff()
    or public.has_course_enrollment(p_course_id)
    or exists (
      select 1
      from public.app_records
      where collection = 'courses'
        and owner_id is null
        and record_id = p_course_id
        and payload ->> 'status' = 'publicado'
    );
$$;

alter table public.app_records enable row level security;
drop policy if exists "Read platform records" on public.app_records;
create policy "Read platform records"
on public.app_records for select to anon, authenticated
using (
  (
    owner_id is null
    and (
      collection in ('settings', 'departments')
      or (
        auth.uid() is not null
        and (
          (collection = 'courses' and public.can_view_course(record_id))
          or (collection = 'lessons' and public.can_view_course(payload ->> 'courseId'))
          or (collection = 'quizzes'
              and (public.is_platform_staff() or public.has_course_enrollment(record_id)))
          or (collection = 'products'
              and (public.is_platform_staff() or payload ->> 'active' = 'true'))
          or collection = 'announcements'
          or (collection = 'audit' and public.is_platform_staff())
        )
      )
    )
  )
  or (auth.uid() is not null and owner_id = auth.uid())
  or (auth.uid() is not null and public.is_platform_staff())
);

drop policy if exists "Insert owned or staff records" on public.app_records;
create policy "Insert owned or staff records"
on public.app_records for insert to authenticated
with check (
  public.is_platform_staff()
  or (
    owner_id = auth.uid()
    and collection in (
      'enrollments', 'progress', 'watch', 'attempts', 'certificates',
      'ratings', 'comments', 'notes', 'favorites', 'redemptions',
      'log', 'notifications'
    )
  )
);

drop policy if exists "Update owned or staff records" on public.app_records;
create policy "Update owned or staff records"
on public.app_records for update to authenticated
using (public.is_platform_staff() or owner_id = auth.uid())
with check (
  public.is_platform_staff()
  or (
    owner_id = auth.uid()
    and collection in (
      'enrollments', 'progress', 'watch', 'attempts', 'certificates',
      'ratings', 'comments', 'notes', 'favorites', 'redemptions',
      'log', 'notifications'
    )
  )
);

drop policy if exists "Delete owned or staff records" on public.app_records;
create policy "Delete owned or staff records"
on public.app_records for delete to authenticated
using (
  public.is_platform_staff()
  or (
    owner_id = auth.uid()
    and collection in (
      'enrollments', 'progress', 'watch', 'attempts', 'certificates',
      'ratings', 'comments', 'notes', 'favorites', 'redemptions',
