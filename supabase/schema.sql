create or replace function public.verify_course_certificate(p_code text)
returns table (
  valid boolean,
  certificate_code text,
  learner_name text,
  course_title text,
  course_category text,
  issued_at timestamptz,
  platform_name text
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    true,
    cert.payload ->> 'code',
    coalesce(profile.name, 'Aluno'),
    coalesce(course.payload ->> 'title', 'Curso removido'),
    course.payload ->> 'category',
    to_timestamp((cert.payload ->> 'at')::double precision / 1000),
    coalesce(settings.payload ->> 'platformName', 'Academia Corporativa')
  from public.app_records cert
  left join public.profiles profile
    on profile.internal_id = (cert.payload ->> 'userId')::bigint
  left join public.app_records course
    on course.collection = 'courses'
   and course.owner_id is null
   and course.record_id = cert.payload ->> 'courseId'
  left join public.app_records settings
    on settings.collection = 'settings'
   and settings.owner_id is null
   and settings.record_id = 'platform'
  where cert.collection = 'certificates'
    and cert.payload ->> 'code' = p_code
  limit 1;
$$;

grant execute on function public.verify_course_certificate(text) to anon, authenticated;

insert into storage.buckets (id, name, public)
values ('course-videos', 'course-videos', false),
       ('course-materials', 'course-materials', false)
on conflict (id) do update set public = false;

drop policy if exists "Read course files" on storage.objects;
create policy "Read course files"
on storage.objects for select to authenticated
using (
  bucket_id in ('course-videos', 'course-materials')
  and public.can_view_course((storage.foldername(name))[1])
);

drop policy if exists "Staff upload course files" on storage.objects;
create policy "Staff upload course files"
on storage.objects for insert to authenticated
with check (
  bucket_id in ('course-videos', 'course-materials')
  and public.is_platform_staff()
);

drop policy if exists "Staff delete course files" on storage.objects;
create policy "Staff delete course files"
on storage.objects for delete to authenticated
using (
  bucket_id in ('course-videos', 'course-materials')
  and public.is_platform_staff()
);
