-- Initial schema for the Academia Corporativa Supabase project.
-- Run in the Supabase SQL Editor before setting LOCAL_MODE to false.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  internal_id bigint generated by default as identity unique not null,
  email text not null,
  name text not null default '',
  role text not null default 'aluno' check (role in ('aluno', 'instrutor', 'admin')),
  dept text not null default '',
  job_title text not null default '',
  active boolean not null default true,
  pending boolean not null default false,
  points integer not null default 0,
  xp integer not null default 0,
  badges jsonb not null default '[]'::jsonb,
  theme text not null default 'auto',
  created_at timestamptz not null default now(),
  last_login timestamptz,
  streak integer not null default 0,
  last_checkin date
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.profiles (id, email, name, dept)
  values (
    new.id,
    lower(coalesce(new.email, '')),
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.raw_user_meta_data ->> 'dept', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_platform_staff()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid()
      and role in ('admin', 'instrutor')
      and active
      and not pending
  );
$$;

create or replace function public.is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid()
      and role = 'admin'
      and active
      and not pending
  );
$$;

create or replace function public.guard_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if current_setting('app.bootstrap_first_admin', true) = 'on' then
    return new;
  end if;
  if (new.role is distinct from old.role
      or new.active is distinct from old.active
      or new.pending is distinct from old.pending)
     and auth.uid() is not null
     and not public.is_platform_admin() then
    raise exception 'Somente um administrador pode alterar perfil ou acesso.';
  end if;
  return new;
end;
$$;

create or replace function public.bootstrap_first_admin(p_email text)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  affected integer;
begin
  if p_email is null or btrim(p_email) = '' then
    raise exception 'Informe o e-mail da conta que será administradora.';
  end if;

  if exists (
    select 1
    from public.profiles
    where role = 'admin'
      and lower(email) <> lower(btrim(p_email))
  ) then
    raise exception 'Outro administrador já existe; bootstrap inicial não é mais permitido.';
  end if;

  perform set_config('app.bootstrap_first_admin', 'on', true);
  update public.profiles
  set role = 'admin', active = true, pending = false
  where lower(email) = lower(btrim(p_email));

  get diagnostics affected = row_count;
  if affected <> 1 then
    raise exception 'Conta não encontrada ou e-mail não exclusivo. Confira o cadastro.';
  end if;
  return affected;
end;
$$;

revoke all on function public.bootstrap_first_admin(text) from public, anon, authenticated;

drop trigger if exists guard_profile_privileges on public.profiles;
create trigger guard_profile_privileges
before update on public.profiles
for each row execute function public.guard_profile_privileges();

